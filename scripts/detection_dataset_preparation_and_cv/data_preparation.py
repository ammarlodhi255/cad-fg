#!/usr/bin/env python3
import os
import shutil
import random
import re
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
from sklearn.model_selection import StratifiedKFold, StratifiedShuffleSplit


# =========================
# CONFIG
# =========================
BASE_DIR = Path("/cluster/home/ammaa/Downloads/meta-cadica/data/cadica_yolo_det")
OUTPUT_DIR = Path("/cluster/home/ammaa/Downloads/meta-cadica/data/det_folds")

N_OUTER = 5
INNER_VAL_RATIO = 0.15
SEED = 42

random.seed(SEED)
np.random.seed(SEED)


# =========================
# SOURCE PATHS (NO TEST)
# =========================
IMAGE_DIRS = [
    BASE_DIR / "train/images",
    BASE_DIR / "val/images",
]

LABEL_DIRS = [
    BASE_DIR / "train/labels",
    BASE_DIR / "val/labels",
]


# =========================
# GROUP IMAGES BY PATIENT
# =========================
def load_patient_data() -> Dict[str, List[Tuple[Path, Path]]]:
    patient_dict = defaultdict(list)
    patient_regex = re.compile(r"(p\d+)_")

    for img_dir, lbl_dir in zip(IMAGE_DIRS, LABEL_DIRS):
        for img_name in os.listdir(img_dir):
            match = patient_regex.match(img_name)
            if not match:
                continue

            pid = match.group(1)
            img_path = img_dir / img_name
            lbl_path = lbl_dir / img_name.replace(".png", ".txt")

            if lbl_path.exists():
                patient_dict[pid].append((img_path, lbl_path))

    return patient_dict


# =========================
# STRATIFICATION LABEL
# =========================
def patient_has_annotation(files: List[Tuple[Path, Path]]) -> int:
    """1 = positive patient, 0 = negative patient"""
    for _, lbl in files:
        if lbl.stat().st_size > 0:
            return 1
    return 0


# =========================
# FILE COPYING
# =========================
def copy_patients(
    patient_ids: List[str],
    patient_dict: Dict[str, List[Tuple[Path, Path]]],
    dst_dir: Path,
) -> int:
    count = 0
    for pid in patient_ids:
        for img_p, lbl_p in patient_dict[pid]:
            shutil.copy(img_p, dst_dir / "images")
            shutil.copy(lbl_p, dst_dir / "labels")
            count += 1
    return count


# =========================
# MAIN PIPELINE
# =========================
def main():
    patient_dict = load_patient_data()
    patients = list(patient_dict.keys())

    print(f"Total patients: {len(patients)}")

    patient_labels = [
        patient_has_annotation(patient_dict[p]) for p in patients
    ]

    outer_kf = StratifiedKFold(
        n_splits=N_OUTER, shuffle=True, random_state=SEED
    )

    for outer_fold, (train_idx, val_idx) in enumerate(
        outer_kf.split(patients, patient_labels), start=1
    ):
        print(f"\n==============================")
        print(f"Outer Fold {outer_fold}")

        outer_train_patients = [patients[i] for i in train_idx]
        outer_val_patients   = [patients[i] for i in val_idx]

        print(f"Outer-Train Patients: {len(outer_train_patients)}")
        print(f"Outer-Val Patients:   {len(outer_val_patients)}")

        # =========================
        # INNER 85 / 15 SPLIT
        # =========================
        inner_labels = [
            patient_labels[patients.index(p)]
            for p in outer_train_patients
        ]

        sss = StratifiedShuffleSplit(
            n_splits=1,
            test_size=INNER_VAL_RATIO,
            random_state=SEED,
        )

        inner_train_idx, inner_val_idx = next(
            sss.split(outer_train_patients, inner_labels)
        )

        inner_train_patients = [
            outer_train_patients[i] for i in inner_train_idx
        ]
        inner_val_patients = [
            outer_train_patients[i] for i in inner_val_idx
        ]

        # =========================
        # CREATE FOLD DIRECTORIES
        # =========================
        fold_dir = OUTPUT_DIR / f"fold_{outer_fold}"
        for split in ["train", "inner_val", "outer_val"]:
            (fold_dir / split / "images").mkdir(parents=True, exist_ok=True)
            (fold_dir / split / "labels").mkdir(parents=True, exist_ok=True)

        # =========================
        # COPY FILES
        # =========================
        train_imgs = copy_patients(
            inner_train_patients, patient_dict, fold_dir / "train"
        )
        inner_val_imgs = copy_patients(
            inner_val_patients, patient_dict, fold_dir / "inner_val"
        )
        outer_val_imgs = copy_patients(
            outer_val_patients, patient_dict, fold_dir / "outer_val"
        )

        print(
            f"Images → "
            f"Train: {train_imgs} | "
            f"Inner-Val: {inner_val_imgs} | "
            f"Outer-Val: {outer_val_imgs}"
        )

    print("\n✅ Patient-wise stratified nested 5-Fold CV completed!")


# =========================
# ENTRY POINT
# =========================
if __name__ == "__main__":
    main()

