import os
import yaml
import json
import time
import argparse
from ultralytics import YOLO
import pandas as pd

# Parse command-line arguments
parser = argparse.ArgumentParser(description='YOLO Nested Cross-Validation Training')
parser.add_argument(
    '--models',
    type=str,
    default='yolov5x,yolov8x,yolo11x,yolo12x,yolo26x,yolov9e',
    help='Comma-separated list of YOLO models (e.g., yolov5x,yolov8x,yolo11x,yolo12x,yolo26x,yolov9e)',
)
parser.add_argument('--epochs', type=int, default=100,
                    help='Number of training epochs')
parser.add_argument('--imgsz', type=int, default=640,
                    help='Image size for training')
parser.add_argument('--batch', type=int, default=16,
                    help='Batch size')
parser.add_argument('--data-dir', type=str, default='data/det_folds',
                    help='Directory containing the fold data')
parser.add_argument('--output-dir', type=str, default='outputs/detection_cv_results',
                    help='Output directory for all results')
parser.add_argument('--search-eval', action='store_true',
                    help='Skip training, search for existing best.pt files and evaluate them')
parser.add_argument('--resume', action='store_true',
                    help='Resume training: skip folds with existing best.pt, train missing ones')
args = parser.parse_args()

BASE_DIR = os.path.abspath(args.data_dir)
NUM_FOLDS = 5
OUTPUT_DIR = os.path.abspath(args.output_dir)  # Use absolute path

# Parse model list
model_list = [m.strip() for m in args.models.split(',')]

print(f"\n{'='*60}")
print(f"🚀 Multi-Model Nested Cross-Validation")
print(f"{'='*60}")
if args.search_eval:
    mode_desc = 'EVALUATION ONLY'
elif args.resume:
    mode_desc = 'RESUME MODE (skip existing, train missing)'
else:
    mode_desc = 'TRAINING + EVALUATION'
print(f"Mode: {mode_desc}")
print(f"Models to train: {model_list}")
print(f"Folds: {NUM_FOLDS}")
if not args.search_eval:
    print(f"Epochs: {args.epochs}, Batch: {args.batch}, ImgSize: {args.imgsz}")
print(f"Output directory: {OUTPUT_DIR}")
print(f"{'='*60}\n")

# Create output directory
os.makedirs(OUTPUT_DIR, exist_ok=True)

# Store all model results for final comparison
all_models_summary = []

# Store all model results for final comparison
all_models_summary = []

# =========================
# LOOP OVER MODELS
# =========================
for model_name in model_list:
    print(f"\n{'='*60}")
    print(f"📦 MODEL: {model_name}")
    print(f"{'='*60}\n")
    
    # Training configuration (for reproducibility)
    TRAINING_CONFIG = {
        "model": f"{model_name}.pt",
        "epochs": args.epochs,
        "imgsz": args.imgsz,
        "batch": args.batch,
        "optimizer": "auto",
    }
    
    # Create model-specific output directory
    model_output_dir = os.path.abspath(os.path.join(OUTPUT_DIR, model_name))
    os.makedirs(model_output_dir, exist_ok=True)
    
    all_fold_results = []
    
    # Test if model exists (only for training mode)
    if not args.search_eval:
        try:
            print(f"🔍 Checking if {TRAINING_CONFIG['model']} is available...")
            test_model = YOLO(TRAINING_CONFIG["model"])
            del test_model  # Clean up
            print(f"✅ Model loaded successfully\n")
        except Exception as e:
            print(f"❌ Error: Model '{model_name}' not available")
            print(f"   Reason: {str(e)}")
            print(f"   Skipping this model...\n")
            continue
    
    # In resume mode, give overview of fold states
    if args.resume:
        print("📋 Checking fold status...")
        for fold_check in range(1, NUM_FOLDS + 1):
            best_check = os.path.join(model_output_dir, "runs", f"fold_{fold_check}", "weights", "best.pt")
            last_check = os.path.join(model_output_dir, "runs", f"fold_{fold_check}", "weights", "last.pt")
            
            if os.path.exists(best_check):
                print(f"  Fold {fold_check}: ✅ Completed")
            elif os.path.exists(last_check):
                print(f"  Fold {fold_check}: 🔄 Incomplete (will resume)")
            else:
                print(f"  Fold {fold_check}: ⏳ Not started")
        print()
    
    # =========================
    # LOOP OVER FOLDS
    # =========================
    for fold in range(1, NUM_FOLDS + 1):
        print(f"\n{'='*50}")
        print(f"🚀 MODEL: {model_name} | FOLD: {fold}/{NUM_FOLDS}")
        print(f"{'='*50}")

        fold_start_time = time.time()
        fold_dir = os.path.abspath(os.path.join(BASE_DIR, f"fold_{fold}"))
        
        # Check if best.pt already exists
        best_weights_locations = [
            os.path.abspath(os.path.join(model_output_dir, "runs", f"fold_{fold}", "weights", "best.pt")),
            os.path.abspath(os.path.join(model_output_dir, "runs", f"fold_{fold}_exp", "weights", "best.pt")),
        ]
        
        # Check if last.pt exists (indicates incomplete training)
        last_weights_locations = [
            os.path.abspath(os.path.join(model_output_dir, "runs", f"fold_{fold}", "weights", "last.pt")),
            os.path.abspath(os.path.join(model_output_dir, "runs", f"fold_{fold}_exp", "weights", "last.pt")),
        ]
        
        existing_best_weights = None
        existing_last_weights = None
        
        for path in best_weights_locations:
            if os.path.exists(path):
                existing_best_weights = path
                break
        
        for path in last_weights_locations:
            if os.path.exists(path):
                existing_last_weights = path
                break
        
        # Determine mode for this fold
        # Skip training only if best.pt exists AND no incomplete training (last.pt without being finished)
        fold_completed = existing_best_weights is not None
        fold_in_progress = existing_last_weights is not None and not fold_completed
        
        skip_training = args.search_eval or (args.resume and fold_completed)

        if skip_training:
            # -----------------------------
            # EVALUATION MODE: Use existing best.pt
            # -----------------------------
            if existing_best_weights is None:
                # Try additional locations for search-eval mode
                possible_paths = [
                    os.path.abspath(os.path.join(OUTPUT_DIR, model_name, "runs", f"fold_{fold}", "weights", "best.pt")),
                ]
                for path in possible_paths:
                    if os.path.exists(path):
                        existing_best_weights = path
                        break
            
            if existing_best_weights is None:
                print(f"⚠️  Warning: No best.pt found for fold {fold}, skipping...")
                continue
            
            print(f"📊 Found existing checkpoint: {existing_best_weights}")
            if args.resume:
                print(f"   ⏭️  Skipping training, evaluating existing model...")
            model = YOLO(existing_best_weights)
            
        else:
            # -----------------------------
            # TRAINING MODE
            # -----------------------------
            if fold_in_progress and args.resume:
                # Resume incomplete training from last.pt
                print(f"🔄 Resuming incomplete training from: {existing_last_weights}")
                model = YOLO(existing_last_weights)
                
                # Resume training from checkpoint
                model.train(
                    resume=True,
                    exist_ok=True
                )
            else:
                # Start fresh training
                print(f"🏋️  Training fold {fold} from scratch...")
                
                # 1️⃣ Create YAML for this fold
                data_yaml = {
                    'path': os.path.abspath(fold_dir),
                    'train': 'train/images',
                    'val': 'inner_val/images',
                    'names': {0: 'lesion'}
                }

                yaml_path = os.path.abspath(os.path.join(fold_dir, "data.yaml"))
                with open(yaml_path, 'w') as f:
                    yaml.dump(data_yaml, f)

                # 2️⃣ Load model
                model = YOLO(TRAINING_CONFIG["model"])

                # 3️⃣ Train (uses INNER VAL)
                model.train(
                    data=yaml_path,
                    epochs=TRAINING_CONFIG["epochs"],
                    imgsz=TRAINING_CONFIG["imgsz"],
                    batch=TRAINING_CONFIG["batch"],
                    name=f"fold_{fold}",
                    project=os.path.abspath(os.path.join(model_output_dir, "runs")),
                    val=True,
                    exist_ok=True  # Allow overwriting existing runs
                )

            # 4️⃣ Load Best Checkpoint
            best_weights = os.path.abspath(os.path.join(model_output_dir, "runs", f"fold_{fold}", "weights", "best.pt"))
            print(f"📊 Loading best checkpoint: {best_weights}")
            model = YOLO(best_weights)
            existing_best_weights = best_weights  # Update for consistency
        
        # -----------------------------
        # Evaluate on OUTER VAL (both modes)
        # -----------------------------
        outer_yaml = {
            'path': os.path.abspath(fold_dir),
            'train': 'train/images',
            'val': 'outer_val/images',
            'names': {0: 'lesion'}
        }

        outer_yaml_path = os.path.abspath(os.path.join(fold_dir, "outer_data.yaml"))
        with open(outer_yaml_path, 'w') as f:
            yaml.dump(outer_yaml, f)

        # Evaluate with proper output directory
        metrics = model.val(
            data=outer_yaml_path,
            project=os.path.abspath(os.path.join(model_output_dir, "val_results")),
            name=f"fold_{fold}_outer_val",
            save=False,  # Don't save prediction images to save space
            exist_ok=True  # Allow overwriting existing validation runs
        )

        eval_time = time.time() - fold_start_time
        
        # Calculate F1 score from precision and recall
        precision = float(metrics.box.p)
        recall = float(metrics.box.r)
        f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0

        fold_metrics = {
            "fold": fold,
            "precision": precision,
            "recall": recall,
            "f1_score": f1,
            "mAP50": float(metrics.box.map50),
            "mAP50-95": float(metrics.box.map),
            "training_time_sec": eval_time if args.search_eval else eval_time,
            "speed_ms": float(metrics.speed['inference']) if hasattr(metrics, 'speed') else None,
        }

        all_fold_results.append(fold_metrics)
        if skip_training:
            if args.search_eval:
                print(f"✅ Fold {fold} evaluated in {eval_time:.2f} seconds")
            else:  # resume mode
                print(f"✅ Fold {fold} skipped (using existing model), evaluated in {eval_time:.2f} seconds")
        elif fold_in_progress and args.resume:
            print(f"✅ Fold {fold} training resumed and completed in {eval_time/60:.2f} minutes")
        else:
            print(f"✅ Fold {fold} completed in {eval_time/60:.2f} minutes")

    # -----------------------------
    # 5️⃣ Save Results for This Model
    # -----------------------------
    df = pd.DataFrame(all_fold_results)
    
    if df.empty:
        print(f"⚠️  No results collected for {model_name}, skipping...")
        continue
    
    results_csv = os.path.abspath(os.path.join(model_output_dir, "fold_results.csv"))
    results_json = os.path.abspath(os.path.join(model_output_dir, "aggregate_metrics.json"))

    df.to_csv(results_csv, index=False)

    # Save aggregate performance to JSON (exclude 'fold' from aggregation)
    metrics_df = df.drop(columns=['fold'])
    aggregate_metrics = metrics_df.mean(numeric_only=True).to_dict()
    aggregate_std = metrics_df.std(numeric_only=True).to_dict()

    # Determine time label and value based on mode
    if args.search_eval:
        time_label = "total_eval_time_sec"
        time_value = float(df['training_time_sec'].sum())
    elif args.resume:
        time_label = "total_time_hours"  # Mix of training + eval time
        time_value = float(df['training_time_sec'].sum() / 3600)
    else:
        time_label = "total_training_time_hours"
        time_value = float(df['training_time_sec'].sum() / 3600)
    
    aggregate_results = {
        "model": model_name,
        "training_config": TRAINING_CONFIG,
        "num_folds": NUM_FOLDS,
        "evaluation_mode": args.search_eval,
        "metrics": {
            "mean": {k: float(v) for k, v in aggregate_metrics.items()},
            "std": {k: float(v) for k, v in aggregate_std.items()},
            "min": {k: float(v) for k, v in metrics_df.min(numeric_only=True).to_dict().items()},
            "max": {k: float(v) for k, v in metrics_df.max(numeric_only=True).to_dict().items()},
        },
        time_label: time_value
    }

    with open(results_json, 'w') as f:
        json.dump(aggregate_results, f, indent=2)

    print(f"\n🏆 RESULTS FOR {model_name}")
    print(df)
    print("\n📊 Average Performance:")
    print(metrics_df.mean(numeric_only=True))
    if args.search_eval:
        print(f"\n⏱️  Total Evaluation Time: {time_value:.2f} seconds")
    elif args.resume:
        print(f"\n⏱️  Total Time: {time_value:.2f} hours (mix of training + evaluation)")
    else:
        print(f"\n⏱️  Total Training Time: {time_value:.2f} hours")
    print(f"\n✅ Model results saved to: {model_output_dir}/")
    
    # Store summary for final comparison
    all_models_summary.append({
        "model": model_name,
        "mAP50": aggregate_results["metrics"]["mean"]["mAP50"],
        "mAP50-95": aggregate_results["metrics"]["mean"]["mAP50-95"],
        "f1_score": aggregate_results["metrics"]["mean"]["f1_score"],
        "precision": aggregate_results["metrics"]["mean"]["precision"],
        "recall": aggregate_results["metrics"]["mean"]["recall"],
        "training_time_hours": time_value if not args.search_eval else None,
    })

# =========================
# 6️⃣ Save Final Model Comparison
# =========================
if len(model_list) > 1:
    comparison_df = pd.DataFrame(all_models_summary)
    comparison_csv = os.path.abspath(os.path.join(OUTPUT_DIR, "model_comparison.csv"))
    comparison_df.to_csv(comparison_csv, index=False)
    
    print(f"\n{'='*60}")
    print("🏅 FINAL MODEL COMPARISON")
    print(f"{'='*60}")
    print(comparison_df.to_string(index=False))
    print(f"\n✅ Comparison saved to: {comparison_csv}")
    
print(f"\n{'='*60}")
if args.search_eval:
    mode_str = "EVALUATION"
elif args.resume:
    mode_str = "RESUME"
else:
    mode_str = "TRAINING"
print(f"✨ ALL {mode_str} COMPLETED!")
print(f"{'='*60}")
